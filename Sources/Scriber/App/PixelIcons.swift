/// A pixel icon at whole or half points per pixel, placed on whole device pixels so it stays sharp.
struct PixelIconView: View {
    var icon: PixelIcon
    var color: Color
    var pixel: CGFloat = 1

    var body: some View {
        Canvas { gc, size in
            let side = CGFloat(PixelIcon.side) * pixel
            let origin = CGPoint(x: ((size.width - side) / 2 * 2).rounded() / 2,
                                 y: ((size.height - side) / 2 * 2).rounded() / 2)
            var path = Path()
            for cell in icon.cells {
                path.addRect(CGRect(x: origin.x + CGFloat(cell.x) * pixel, y: origin.y + CGFloat(cell.y) * pixel,
                                    width: pixel, height: pixel))
            }
            gc.fill(path, with: .color(color))
        }
        .frame(width: CGFloat(PixelIcon.side) * pixel, height: CGFloat(PixelIcon.side) * pixel)
        .accessibilityHidden(true)
    }
}
