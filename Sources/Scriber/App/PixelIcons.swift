        }
    }

    /// For AppKit drawing (the draft's margin and locks). `pixel` is points per pixel.
    func image(color: NSColor, pixel: CGFloat = 1) -> NSImage {
        let side = CGFloat(Self.side) * pixel
        let cells = self.cells
        let image = NSImage(size: NSSize(width: side, height: side), flipped: true) { _ in
            color.setFill()
            for cell in cells {
                NSRect(x: CGFloat(cell.x) * pixel, y: CGFloat(cell.y) * pixel, width: pixel, height: pixel).fill()
            }
            return true
        }
        return image
    }
